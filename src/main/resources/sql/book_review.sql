CREATE TABLE BOOK_REVIEW (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BOOK_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    REVIEW_TEXT VARCHAR(10000) NOT NULL,
    SCORE INTEGER NOT NULL,

    CONSTRAINT UK_BOOK_REVIEW_USER_BOOK UNIQUE (USER_ID, BOOK_ID),
    CONSTRAINT FK_BOOK_REVIEW_BOOK FOREIGN KEY (BOOK_ID) REFERENCES BOOK(ID),
    CONSTRAINT FK_BOOK_REVIEW_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(ID),
    CONSTRAINT CK_BOOK_REVIEW_SCORE CHECK (SCORE BETWEEN 0 AND 10),
    CONSTRAINT CK_BOOK_REVIEW_TEXT CHECK (CHAR_LENGTH(TRIM(REVIEW_TEXT)) > 0)
);
